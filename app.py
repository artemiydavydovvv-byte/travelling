def _match_inner():
    if not HOTELS_FILE.exists():
        return jsonify({"error": "hotels.json not found — run travellingai.py first"}), 500

    data = request.get_json(force=True)
    user_input = (data.get("query") or "").strip()
    if not user_input:
        return jsonify([])

    from datetime import date, timedelta
    today     = date.today()
    check_in  = str(today + timedelta(days=10))
    check_out = str(today + timedelta(days=14))

    hotels = json.loads(HOTELS_FILE.read_text(encoding="utf-8"))

    avoid_text      = (data.get("avoidances") or "").strip()
    query_b         = (data.get("query_b") or "").strip()
    scores_override = data.get("scores_override")  # dict of {dim: value} from refine

    if scores_override:
        # Refine mode: skip Claude, use boosted scores directly
        user_scores = {k: int(scores_override.get(k, 5)) for k in _SCORE_KEYS}
        budget_usd  = float(data.get("budget_usd") or 0)
        avoidances  = data.get("avoidances_list") or []
        pitch_input = user_input
    elif query_b:
        # Two-person mode: score each person separately then average
        with ThreadPoolExecutor(max_workers=2) as ex:
            fa = ex.submit(feeling_to_scores, f"{user_input}\n\nThings to avoid: {avoid_text}" if avoid_text else user_input)
            fb = ex.submit(feeling_to_scores, query_b)
            scores_a = fa.result()
            scores_b = fb.result()

        budget_a = scores_a.pop("budget_usd", 0)
        budget_b = scores_b.pop("budget_usd", 0)
        avoid_a  = scores_a.pop("avoidances", [])
        avoid_b  = scores_b.pop("avoidances", [])

        user_scores = {k: round((scores_a.get(k, 5) + scores_b.get(k, 5)) / 2) for k in _SCORE_KEYS}
        budget_usd  = min(b for b in [budget_a, budget_b] if b > 0) if any([budget_a, budget_b]) else 0
        avoidances  = list(set(avoid_a + avoid_b))
        pitch_input = f"Person A wants: {user_input}\nPerson B wants: {query_b}"
    else:
        full_input  = f"{user_input}\n\nThings to avoid: {avoid_text}" if avoid_text else user_input
        user_scores = feeling_to_scores(full_input)
        budget_usd  = user_scores.pop("budget_usd", 0)
        avoidances  = user_scores.pop("avoidances", [])
        pitch_input = user_input

    if budget_usd > 0:
        filtered = [
            h for h in hotels
            if _parse_price(h.get("Price (total)", "")) <= budget_usd
            or _parse_price(h.get("Price (total)", "")) == 0
        ]
        hotels = filtered if filtered else hotels

    if avoidances:
        filtered = [h for h in hotels if _passes_avoidance(h, avoidances)]
        hotels = filtered if len(filtered) >= 5 else hotels  # fall back if too aggressive

    compute_match(hotels, user_scores)

    if scores_override:
        by_match = sorted(hotels, key=lambda h: h.get("Match %", 0), reverse=True)
        role_labels = ["safe", "gem", "wildcard"]
        results = []
        for i, h in enumerate(by_match):
            role = role_labels[i] if i < 3 else "match"
            entry = {**h, "_role": role}
            if i >= 3:
                entry["_rank"] = i + 1
            results.append(entry)
        editorial = []
    else:
        results = select_all(hotels)
        editorial = results[:3]

    # Only check availability for first page (10 hotels) — rest loaded lazily
    page1 = results[:10]
    with ThreadPoolExecutor(max_workers=13) as ex:
        pitch_futures = {
            ex.submit(generate_pitch, pitch_input, h, h["_role"]): i
            for i, h in enumerate(editorial)
        }
        avail_futures = {
            ex.submit(check_availability, h, check_in, check_out, 2, 1): i
            for i, h in enumerate(page1)
        }
        for f in as_completed(pitch_futures):
            editorial[pitch_futures[f]]["pitch"] = f.result()
        for f in as_completed(avail_futures):
            page1[avail_futures[f]].update(f.result())

    for h in results:
        h["_check_in"]  = check_in
        h["_check_out"] = check_out

    return jsonify({
        "hotels": results,
        "scores": user_scores,
        "budget_usd": budget_usd,
        "avoidances_list": avoidances,
        "check_in": check_in,
        "check_out": check_out,
    })


@app.route("/avail", methods=["POST"])
def avail():
    data = request.get_json(force=True)
    hotels_data = data.get("hotels") or []
    check_in  = data.get("check_in", "")
    check_out = data.get("check_out", "")
    results = [None] * len(hotels_data)
    with ThreadPoolExecutor(max_workers=10) as ex:
        futures = {
            ex.submit(check_availability, h, check_in, check_out, 2, 1): i
            for i, h in enumerate(hotels_data)
        }
        for f in as_completed(futures):
            results[futures[f]] = f.result()
    return jsonify(results)


