_SCORE_KEYS = ["novelty", "remoteness", "romance", "intensity", "visual_awe", "luxury", "story_worthiness"]

_SCORE_SYSTEM = """\
You are a travel-preference classifier. Given a user's travel desire and optionally what they want to avoid,
return ONLY a JSON object with exactly these keys:
  novelty, remoteness, romance, intensity, visual_awe, luxury, story_worthiness — integers 0 to 10
  budget_usd — total trip budget converted to USD, or 0 if not mentioned
  avoidances — a list of lowercase words/short phrases to screen out from hotel names, vibes and descriptions
               Examples: ["resort", "hostel", "family", "party", "shared", "chain", "corporate", "crowded", "golf"]
               Return [] if nothing to avoid.

Scoring rules — be PRECISE and BOLD:
- Use the FULL 0–10 range. Do not cluster everything around 5–7.
- If the user emphasises a dimension ("really luxury", "super romantic", "extremely remote", "big adventure"),
  score it 9 or 10. One keyword = 8; one strong keyword = 9-10.
- Dimensions the user does NOT mention should stay at 5 (neutral).
- If the user explicitly rejects something ("no parties", "not touristy", "simple not luxury"), score it 0–2.
- "Chill", "relax", "peaceful", "quiet" → intensity 1-3, remoteness 6-8, luxury 5-6.
- "Luxury", "high-end", "5-star", "expensive", "lavish" → luxury 9-10.
- "Adventure", "extreme", "intense" → intensity 9-10.
- "Romantic", "couples", "honeymoon" → romance 9-10.
- "Off the grid", "isolated", "no one around" → remoteness 9-10.
- "Unique", "unusual", "never heard of" → novelty 9-10.
- "Scenic", "beautiful views", "dramatic landscape" → visual_awe 9-10.

No explanation, no markdown, no extra keys — just the JSON object."""

_PITCH_SYSTEMS = {
    "safe": """\
You are a travel writer. Write 2-3 sentences like a trusted friend who has been there and loved it.
Warm, reassuring, confident. The reader should feel: "I know I won't regret this."
No bullet points, no headers. Speak directly to the traveller.""",

    "gem": """\
You are a travel writer. Write 2-3 sentences like you are letting someone in on a rare secret find.
Excited, slightly conspiratorial. The reader should feel: "I need to tell everyone about this."
No bullet points, no headers. Speak directly to the traveller.""",

    "wildcard": """\
You are a travel writer. Write 2-3 sentences that are bold, honest, slightly provocative.
This place might not be for everyone — and that is the whole point.
The reader should feel: "This is the one that makes a real story."
No bullet points, no headers. Speak directly to the traveller.""",
}

_DIMENSION_MAP = [
    ("novelty",          "Novelty"),
    ("remoteness",       "Remoteness"),
    ("romance",          "Romance"),
    ("intensity",        "Intensity"),
    ("visual_awe",       "Visual Awe"),
    ("luxury",           "Luxury"),
    ("story_worthiness", "Story Worthiness"),
]


def feeling_to_scores(user_input: str) -> dict:
    client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)
    msg = client.messages.create(
        model="claude-opus-4-7",
        max_tokens=256,
        system=_SCORE_SYSTEM,
        messages=[{"role": "user", "content": user_input}],
    )
    text = msg.content[0].text.strip()
    if text.startswith("```"):
        parts = text.split("```")
        text = parts[1].lstrip("json").strip() if len(parts) > 1 else text
    raw = json.loads(text)
    scores = {k: int(raw[k]) for k in _SCORE_KEYS if k in raw}
    scores["budget_usd"]  = float(raw.get("budget_usd") or 0)
    scores["avoidances"]  = [str(a).lower() for a in (raw.get("avoidances") or [])]
    return scores


def _parse_price(price_str) -> float:
    import re
    nums = re.findall(r"[\d]+\.?\d*", str(price_str).replace(",", ""))
    return float(nums[0]) if nums else 0.0


def _passes_avoidance(hotel: dict, avoidances: list) -> bool:
    if not avoidances:
        return True
    text = " ".join([
        str(hotel.get("Name", "")),
        str(hotel.get("Vibe", "")),
        str(hotel.get("Destination", "")),
    ]).lower()
    return not any(term in text for term in avoidances)


def compute_match(rows: list, user_scores: dict) -> None:
    for row in rows:
        dist, weight_total = 0.0, 0.0
        for key, col in _DIMENSION_MAP:
            val = row.get(col)
            if isinstance(val, (int, float)):
                # Dimensions the user cares strongly about (far from neutral 5) count more
                weight = 1.0 + abs(user_scores[key] - 5) / 5.0  # range 1.0–2.0
                dist += abs(val - user_scores[key]) * weight
                weight_total += 10.0 * weight
        row["Match %"] = round((1 - dist / weight_total) * 100) if weight_total else 0


def generate_pitch(user_feeling: str, hotel: dict, role: str = "safe") -> str:
    client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)
    listing = (
        f"Hotel: {hotel.get('Name', '')}\n"
        f"Destination: {hotel.get('Destination', '')}\n"
        f"Vibe: {hotel.get('Vibe', '')}\n"
        f"Stars: {hotel.get('Stars', '')}\n"
        f"Rating: {hotel.get('Rating', '')} ({hotel.get('Reviews', '')} reviews)\n"
        f"Price (total stay): {hotel.get('Price (total)', '')}\n"
        f"Scores — Novelty: {hotel.get('Novelty')}, Remoteness: {hotel.get('Remoteness')}, "
        f"Romance: {hotel.get('Romance')}, Intensity: {hotel.get('Intensity')}, "
        f"Visual Awe: {hotel.get('Visual Awe')}, Luxury: {hotel.get('Luxury')}"
    )
    msg = client.messages.create(
        model="claude-opus-4-7",
        max_tokens=220,
        system=_PITCH_SYSTEMS.get(role, _PITCH_SYSTEMS["safe"]),
        messages=[{"role": "user", "content": f"Traveller's desire: {user_feeling}\n\n{listing}"}],
    )
    return msg.content[0].text.strip()


def select_all(hotels: list) -> list:
    by_match = sorted(hotels, key=lambda h: h.get("Match %", 0), reverse=True)

    # Destination diversity: at most 2 hotels per destination
    dest_count: dict = {}
    diverse = []
    for h in by_match:
        dest = h.get("Destination", "")
        if dest_count.get(dest, 0) < 2:
            diverse.append(h)
            dest_count[dest] = dest_count.get(dest, 0) + 1
    if len(diverse) >= 15:
        by_match = diverse

    top10 = by_match[:min(10, len(by_match))]
    safe = max(top10, key=lambda h: float(h.get("Rating") or 0))

    pool20 = [h for h in by_match[:min(20, len(by_match))] if h is not safe]
    gem = max(pool20, key=lambda h: (h.get("Novelty") or 0) + (h.get("Match %", 0) / 10)) if pool20 else by_match[1]

    pool50 = [h for h in by_match[:min(50, len(by_match))] if h is not safe and h is not gem]
    wildcard = max(pool50, key=lambda h: (h.get("Novelty") or 0) + (h.get("Intensity") or 0)) if pool50 else by_match[2]

    editorial_names = {safe.get("Name"), gem.get("Name"), wildcard.get("Name")}
    remaining = [h for h in by_match if h.get("Name") not in editorial_names]

    return [
        {**safe,     "_role": "safe"},
        {**gem,      "_role": "gem"},
        {**wildcard, "_role": "wildcard"},
    ] + [{**h, "_role": "match", "_rank": i + 4} for i, h in enumerate(remaining)]


